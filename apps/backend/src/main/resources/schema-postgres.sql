ALTER TABLE IF EXISTS manga_library_entry ADD COLUMN IF NOT EXISTS catalog_year INTEGER;
ALTER TABLE IF EXISTS manga_library_entry ADD COLUMN IF NOT EXISTS catalog_genres VARCHAR(1200);
ALTER TABLE IF EXISTS manga_library_entry ADD COLUMN IF NOT EXISTS catalog_authors VARCHAR(1200);
UPDATE manga_library_entry SET read_volumes = 0 WHERE read_volumes IS NULL;
UPDATE manga_library_entry SET total_volumes = 0 WHERE total_volumes IS NULL;
ALTER TABLE IF EXISTS account_message ADD COLUMN IF NOT EXISTS image_data BYTEA;
