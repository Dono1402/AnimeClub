CREATE EXTENSION IF NOT EXISTS pg_trgm;

ALTER TABLE IF EXISTS compte ADD COLUMN IF NOT EXISTS legacy_pseudo VARCHAR(80);
ALTER TABLE IF EXISTS compte ADD COLUMN IF NOT EXISTS username_change_required BOOLEAN;
ALTER TABLE IF EXISTS compte ADD COLUMN IF NOT EXISTS last_active_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE IF EXISTS compte ADD COLUMN IF NOT EXISTS show_online_discovery BOOLEAN DEFAULT false;
ALTER TABLE IF EXISTS compte ALTER COLUMN password TYPE VARCHAR(255);

CREATE TABLE IF NOT EXISTS account_session (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER NOT NULL,
    token_hash VARCHAR(96) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_account_session_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_account_session_account FOREIGN KEY (account_id) REFERENCES compte(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS feed_activity_like (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER NOT NULL,
    activity_owner_id INTEGER NOT NULL,
    activity_type VARCHAR(20) NOT NULL,
    activity_entry_id INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_feed_activity_like_account_activity UNIQUE (account_id, activity_type, activity_entry_id),
    CONSTRAINT fk_feed_activity_like_account FOREIGN KEY (account_id) REFERENCES compte(id) ON DELETE CASCADE,
    CONSTRAINT fk_feed_activity_like_owner FOREIGN KEY (activity_owner_id) REFERENCES compte(id) ON DELETE CASCADE
);

ALTER TABLE IF EXISTS anime_library_entry ADD COLUMN IF NOT EXISTS media_type VARCHAR(40);
ALTER TABLE IF EXISTS manga_library_entry ADD COLUMN IF NOT EXISTS read_volumes INTEGER DEFAULT 0;
